function currentLocale() {
    return LocaleStore?.locale ?? LocaleStore?.systemLocale ?? "en-US";
}

function formatTemplate(template: string, vars?: TranslationVars) {
    if (!vars) return template;

    return template.replaceAll(/\{(\w+)\}/g, (_full, key) => {
        const value = vars[key];
        return value == null ? "" : String(value);
    });
}

function isJapaneseLocale(locale: string) {
    return locale.toLowerCase().startsWith("ja");
}

function translate(locale: string, text: string, vars?: TranslationVars) {
    if (!isJapaneseLocale(locale)) return formatTemplate(text, vars);

    const translated = jaJP[text];
    if (typeof translated === "function")
        return translated(vars ?? {});

    return formatTemplate(translated ?? text, vars);
}

export function translateSettingsText(text: string, vars?: TranslationVars) {
    return translate(currentLocale(), text, vars);
}

export function useSettingsI18n() {
    const locale = useStateFromStores(
        [LocaleStore],
        () => LocaleStore?.locale ?? LocaleStore?.systemLocale ?? "en-US"
    );

    return (text: string, vars?: TranslationVars) => translate(locale, text, vars);
}
